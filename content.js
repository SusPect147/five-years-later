  /** Сколько месяцев подряд может пройти без крупного события. */
  var MAX_GAP = 1;

  function densify(list, months) {
    var manual = list.slice().sort(function (a, b) { return a.month - b.month; });
    var taken = {};
    manual.forEach(function (x) { taken[x.month] = true; });

    // Идём по всем месяцам подряд и занимаем свободные так, чтобы между
    // крупными ситуациями не оставалось больше MAX_GAP пустых месяцев.
    // Ручные слоты не двигаем и не дублируем: сюжет сценария главнее ритма.
    var extra = [], turn = 0, last = -MAX_GAP - 1;
    for (var m = 0; m < months; m++) {
      if (taken[m]) { last = m; continue; }
      if (m - last <= MAX_GAP) continue;
      extra.push({ month: m, tags: FILL_TAGS[turn++ % FILL_TAGS.length] });
      taken[m] = true;
      last = m;
    }
    return manual.concat(extra).sort(function (a, b) { return a.month - b.month; });
  }

  /** Стандартная сетка слотов: удобный помощник, чтобы не дублировать. */
  function slots(list, months) {
    return densify(list.map(function (x) { return { month: x[0], tags: x[1] }; }),
                   months || 60);
  }

